/// Tamil letters with their writing order, in a normalized 0..1 square. Each
/// entry is a list of strokes; each stroke is one pen-down motion the child
/// traces without lifting.
///
/// All 34 characters are here: 12 vowels and 22 consonants.
///
/// The letterforms are the bundled Noto glyph - there is no handwriting to
/// trace for Tamil, as there was for the Malayalam vowels - so only the
/// *order* is authored. A font records where the ink sits and never the order
/// a hand laid it down, so none of this is recoverable from the glyph; it is
/// walked from junction to junction along a route Athul named.
///
/// Two things a chain of junctions cannot say, and which had to be asked for:
/// which way round a closed loop turns (it starts and ends at the same point,
/// so nothing in the geometry distinguishes the two), and which of two routes
/// between the same pair of junctions the pen takes.
