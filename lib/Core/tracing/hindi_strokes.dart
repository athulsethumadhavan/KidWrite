/// Hindi (Devanagari) vowels with their real writing order, in a normalized
/// 0..1 square. Each entry is a list of strokes; each stroke is one pen-down
/// motion the child traces without lifting.
///
/// Recovered from a Devanagari handwriting animation rather than from a font.
/// The animation fills each letter progressively, so the frame at which every
/// pixel takes its ink gives the order and direction the pen moved - which is
/// information no font contains. The path is then snapped onto the letter's
/// skeleton so it runs down the middle of the stroke.
///
/// The shirorekha (the bar across the top) is drawn last throughout, which is
/// how Devanagari is taught.
///
/// Consonants are not here yet and still fall back to free tracing over the
/// bundled Noto glyph (see WritingBloc).
